$MOD51
; Практическая работа 4, вариант 1
; Передача 10 байт в синхронном режиме 0 через последовательный порт.
; Частота кварца 12 МГц; частота CLK на P3.0 равна Fosc/12 = 1 МГц.
; В режиме 0 линия P3.0 (TxD) выдаёт тактовые импульсы,
; а P3.1 (RxD) передаёт данные младшим битом вперёд.

ORG 0000H
    LJMP START

ORG 0030H
START:
    ; Исходные данные ASCII «A»...«J» в резидентной RAM 50h...59h
    MOV 50H, #41H
    MOV 51H, #42H
    MOV 52H, #43H
    MOV 53H, #44H
    MOV 54H, #45H
    MOV 55H, #46H
    MOV 56H, #47H
    MOV 57H, #48H
    MOV 58H, #49H
    MOV 59H, #4AH

    MOV SCON, #00H     ; режим 0, приём запрещён
    CLR TI             ; очистить флаг передатчика
    MOV R0, #50H       ; адрес первого байта
    MOV R2, #0AH       ; всего 10 байт

TX_NEXT:
    MOV A, @R0
    MOV SBUF, A        ; начать передачу одного байта
TX_WAIT:
    JNB TI, TX_WAIT    ; дождаться завершения 8 бит
    CLR TI
    INC R0
    DJNZ R2, TX_NEXT

STOP:
    SJMP STOP          ; после 10 байт оставить порт в покое

END
